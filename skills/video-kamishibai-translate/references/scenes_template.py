"""紙芝居のシーン定義の雛形。コピーして scenes.py にし、CARDS を埋める。

CARDS の各カード (card() の引数):
  sec      SECTIONS の添字。カード上部のチップに表示される (話題・議題・場面の切れ目ごとに分ける)
  t0,t1    動画内の絶対時刻。秒の数値のほか、書き起こしの表記のまま "84:01" "1:24:01.5" (m:ss / h:mm:ss) の文字列でも書ける。
           表示は m:ss (1時間以上は h:mm:ss) に丸められる
  frame    frames_dir の f_<秒>.jpg の <秒>。同じ画面が続くカードは同じ値にすると、画像が1回だけ埋め込まれ、
           同じ話題 (sec) の連続カードは1ページにまとめて表示される (画像は固定、発言が縦に並ぶ。上限は GROUP_MAX)。
           None にすると画像なしの文章だけのカードになる (画面に情報がない場面、人物の顔を載せたくない場面など)
  ja       日本語 (ナレーション)。紙芝居調の「です・ます」で読み上げやすく。句点 (。) ごとに改行して表示されるので、
           1文を短くし、「。」は文末にだけ置く。日本語の動画では、翻訳ではなく書き起こしを整えた文章にする
  en       原文 (動画の言語)。音声認識の結果を使い、言い淀みだけ軽く整える (語句の差し替えは note / NOTES に記録)。
           日本語の動画では省略 (空) にする。フィールド名は en だが、他言語の動画ではその言語の原文を入れる
  speaker  話者 (任意)。会議・対談・座談会で使う。音声だけでは断定できないので、推定なら「Aさん (推測)」のように書く
  ocr      画面内テキストの (原文, 訳) の組。その画面が最初に出るカードにだけ書く。
           同じ画面が続くカードでは省略する。日本語の動画では、日本語の画面文字は訳が要らないので書かない
           (外国語がまとまって映る場面だけ、原文→訳を書く)
  hl       画像上の強調枠 [left%, top%, width%, height%]。今話している領域を示すとき
  note     そのカード固有の補足 (聞き取り不確実、映像からの推測、補正した語など)

SUMMARY (必須) は最初のページに出る「1分サマリー」。
  lead + points (5つ前後。h は省略可) の本文で 300〜700 文字、blocks を含めた合計で 1000 文字以内が目安
  (build 時に文字数が表示され、範囲外なら警告が出る。blocks は本文の文字数に含めない)。
  blocks (任意) で、見出し付きの箇条書きを足せる。会議なら「決定事項」「論点・未決事項」「ToDo」、
  チュートリアルなら「用意するもの」「つまずきやすい点」など。動画で言われたことだけを書き、担当者や期限を補わない。

GLOSSARY (任意) は、その動画の分野の初心者向けに、用語の横へ「？」を付けて意味をポップアップ表示する辞書。
  ユーザーが不要と答えたときは、GLOSSARY を丸ごと省く (定義も用語選定も説明文も書かない。「？」も用語集も出ない)。
  「？」はスイッチなしで常に表示される。match は日本語の本文・画面内テキストの訳・サマリーに実際に出てくる表記。
  desc は動画の発言ではなく訳者の補足なので、確信が持てない説明は書かない。
"""

# 動画の音声の言語コード。"en" (既定、翻訳+原文併記) / "ja" (翻訳せず整形、原文欄なし) / "zh" "ko" など (日本語へ翻訳+原文併記)
SRC_LANG = "en"

# 同じ画面・同じ話題の連続カードを1ページにまとめる上限 (発言数)。省略時は 8、1 ならまとめない
# GROUP_MAX = 8

TITLE = "動画タイトル — 紙芝居 (開始〜終了)"
SUBTITLE = "ファイル名.mp4 の該当区間を、動画キャプチャ付きで日本語にまとめました。最初のページに1分サマリーがあります。← → キーまたはボタンで進み、画像クリックで拡大できます。"

SECTIONS = [
    "スライド「…」 / 議題1 / 手順1 など、話題や場面のまとまりの名前",
    "デモ① … / 議題2 / 手順2 など",
]

CARDS = []


def card(sec, t0, t1, frame, ja, en="", ocr=(), hl=None, note=None, speaker=None):
    CARDS.append(dict(sec=sec, t0=t0, t1=t1, frame=frame, ja=ja, en=en,
                      ocr=[list(o) for o in ocr], hl=hl, note=note, speaker=speaker))


# --- 例: スライドが続く区間 (ocr は最初のカードだけ) ---
card(0, 125.0, 133.5, 125,
     ja="今日は、新しいデータ基盤についてお話しします。まず、現状の課題から見ていきましょう。",
     en="Today I'd like to talk about our new data platform. Let's start with the current challenges.",
     ocr=[("Agenda", "アジェンダ"), ("Current challenges", "現状の課題")],
     note="音声認識は「data plat form」と出力。文脈から「data platform」に補正しました。")

# --- 例: 同じ画面のままナレーションだけ続く (ocr 省略、frame を同じ値に) ---
card(0, 133.5, 150.0, 125,
     ja="データが部門ごとに分かれていて、横断して分析するのに時間がかかっています。",
     en="Data is split across departments, and it takes a long time to analyze it end to end.")

# --- 例: 画面が変わる + 強調枠 ---
card(1, 150.0, 158.0, 152,
     ja="新しい基盤の全体像は、この図のとおりです。右側が、利用者向けの画面になります。",
     en="This diagram shows the overall architecture. The right side is the user-facing screen.",
     hl=[58.4, 20.0, 35.0, 60.0])

# --- 例: 会議・対談 (日本語の動画なら SRC_LANG = "ja"、en は省略。画像なしのカードと話者) ---
