    "ナレーションは <使った書き起こし手段> による音声認識の結果を、文脈から補正して翻訳しています。時刻は認識結果のタイムスタンプに基づく概算です。",
    "音声認識の聞き間違いを次のとおり補正しました: 「A」→「B」、…",
